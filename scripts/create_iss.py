def render(version: str) -> str:
    """The complete ``.iss`` content, with every path absolute and real."""
    # Inno accepts only .ico/.exe/.dll as SetupIconFile, and the built exe is
    # 18 MB — far past its icon-resource limit ("File is too large"). The
    # generated .ico is therefore a prerequisite, not a nicety; an earlier
    # chain fell back to vite.svg, which Inno would have refused anyway.
    setup_icon = REPO / "desktop" / "icons" / "zaytoon.ico"
    if not setup_icon.is_file():
        raise SystemExit(
            f"Cannot compile the installer: {setup_icon} is missing.\n"
            "Generate it first:  backend\\.venv\\Scripts\\python.exe desktop\\icons\\make_icon.py"
        )
    output_dir = REPO / "installer" / "dist"
    return TEMPLATE.format(
        version=version,
        bundle=str(BUNDLE_DIR),
        setup_icon=str(setup_icon),
        output=str(output_dir),
    )


def find_iscc() -> str | None:
    """The Inno Setup compiler, or ``None`` when it is not installed."""
    import shutil

    on_path = shutil.which("ISCC") or shutil.which("ISCC.exe")
    if on_path:
        return on_path
    import os

    for candidate in ISCC_CANDIDATES:
        expanded = os.path.expandvars(candidate)
        if Path(expanded).is_file():
            return expanded
    return None


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate (and optionally compile) the installer")
    parser.add_argument("--compile", action="store_true", help="run ISCC on the generated script")
    parser.add_argument(
        "--allow-missing-bundle",
        action="store_true",
        help="generate the .iss even without a built bundle (for editing, not shipping)",
    )
    args = parser.parse_args(argv)

    problems = [] if args.allow_missing_bundle else check_bundle()
    if problems:
        print("Cannot generate the installer:")
        for problem in problems:
            print(f"  - {problem}")
        return 1

    version = read_version()
    ISS_PATH.parent.mkdir(parents=True, exist_ok=True)
    content = render(version)
    ISS_PATH.write_text(content, encoding="utf-8", newline="\r\n")
    print(f"wrote {ISS_PATH} (version {version})")

    if not args.compile:
        print(f"compile it with:  \"{find_iscc() or 'ISCC'}\" \"{ISS_PATH}\"")
        return 0

    iscc = find_iscc()
    if iscc is None:
        print(
            "ISCC.exe not found. Install Inno Setup 6:\n"
            "    winget install JRSoftware.InnoSetup"
        )
        return 1
    result = subprocess.run([iscc, str(ISS_PATH)])
    if result.returncode != 0:
        return result.returncode
    setup = REPO / "installer" / "dist" / f"Zaytoon-Setup-{version}.exe"
    if setup.is_file():
        size_mb = setup.stat().st_size / (1024 * 1024)
        print(f"built {setup}  ({size_mb:.1f} MB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
