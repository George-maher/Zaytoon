#!/usr/bin/env python
"""Generate ``installer/zaytoon.iss`` — the Inno Setup script for Zaytoon.

    python scripts/create_iss.py            # regenerate installer/zaytoon.iss
    python scripts/create_iss.py --compile  # …then compile it with ISCC

The generator exists because a hand-edited ``.iss`` already shipped broken
once: a non-raw Python string turned ``\\frontend`` into a form-feed + ``rontend``
(``\\f`` is a control character), so the ``[Files]`` section pointed at paths
that never existed and the installer silently carried no frontend at all. This
script writes the file from a **raw** template, resolves the bundle location
relative to the repository, and stamps the version from one place.

What the script guarantees (each one was a real defect):

* paths are absolute and real — a missing bundle is an error here, not an
  empty installer later;
* the version comes from ``desktop/app/__init__.py`` so the installer, the
  shell and the bundle marker cannot disagree;
* ``PrivilegesRequiredOverridesAllowed`` lets the user choose a per-user or an
  all-users install from one artifact;
* ``CloseApplications`` stops a running Zaytoon from blocking an upgrade with
  a file lock;
* the uninstaller never deletes ``%LOCALAPPDATA%\\Zaytoon`` — the user's
  database, reminders and settings — unless the user opts in at uninstall time;
* the ``[Code]`` section checks for the WebView2 runtime before the first
  launch, because a machine without it shows a blank window and no error.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
ISS_PATH = REPO / "installer" / "zaytoon.iss"
#: The onedir bundle ``desktop/scripts/build_exe.py`` produces.
BUNDLE_DIR = REPO / "desktop" / "dist" / "Zaytoon"
#: Inno's compiler, probed in the standard install locations when not on PATH.
ISCC_CANDIDATES = (
    r"%LOCALAPPDATA%\Programs\Inno Setup 6\ISCC.exe",
    r"%ProgramFiles(x86)%\Inno Setup 6\ISCC.exe",
    r"%ProgramFiles%\Inno Setup 6\ISCC.exe",
)


def read_version() -> str:
    """The single version the shell reports (``app.__version__``)."""
    init = REPO / "desktop" / "app" / "__init__.py"
    match = re.search(r'__version__\s*=\s*["\']([^"\']+)["\']', init.read_text(encoding="utf-8"))
    if not match:
        raise SystemExit(f"cannot find __version__ in {init}")
    return match.group(1)


def check_bundle() -> list[str]:
    """Problems that would produce an installer shipping nothing."""
    problems: list[str] = []
    exe = BUNDLE_DIR / ("Zaytoon.exe" if sys.platform == "win32" else "Zaytoon")
    if not exe.is_file():
        problems.append(
            f"the desktop bundle is missing ({exe}). Build it first:\n"
            f"    python desktop/scripts/build_exe.py"
        )
    if not (BUNDLE_DIR / "_internal" / "backend" / "main.py").is_file():
        problems.append(f"the bundle has no backend tree ({BUNDLE_DIR / '_internal' / 'backend'})")
    if not (BUNDLE_DIR / "_internal" / "frontend" / "index.html").is_file():
        problems.append(
            f"the bundle has no frontend ({BUNDLE_DIR / '_internal' / 'frontend' / 'index.html'})"
        )
    return problems


